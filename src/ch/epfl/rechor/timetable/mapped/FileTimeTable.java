package ch.epfl.rechor.timetable.mapped;

import ch.epfl.rechor.timetable.*;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.ByteBuffer;
import java.nio.channels.FileChannel;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.List;

/**
 * FileTimeTable is an immutable representation of timetable data mapped in memory.
 * This class implements the TimeTable interface and provides access to stations,
 * station aliases, platforms, routes, transfers, trips and connections by loading
 * data from binary files in a given directory. The compact constructor generated by
 * the record ensures the instance is immutable.
 *
 * @param directory    the directory containing the binary files
 * @param stringTable  the table of strings read from strings.txt
 * @param stations     the stations data
 * @param stationAliases the station aliases data
 * @param platforms    the platforms data
 * @param routes       the routes data
 * @param transfers    the transfers data
 *
 * @author Amine Lotfi Senhadji
 * @author Nadine Jegham
 */
public record FileTimeTable(
        Path directory,
        List<String> stringTable,
        Stations stations,
        StationAliases stationAliases,
        Platforms platforms,
        Routes routes,
        Transfers transfers
) implements TimeTable {

    /**
     * Loads the timetable data from the specified directory.
     *
     * @param directory the directory containing the timetable binary files
     * @return a TimeTable instance with the loaded data
     * @throws IOException if an I/O error occurs reading the files
     */
    public static TimeTable in(Path directory) throws IOException {
        Path strings = directory.resolve("strings.txt");
        List<String> stringTable =
                List.copyOf(Files.readAllLines(strings, StandardCharsets.ISO_8859_1));

        ByteBuffer stationsBuffer;
        try (FileChannel ch = FileChannel.open(directory.resolve("stations.bin"))) {
            stationsBuffer = ch.map(FileChannel.MapMode.READ_ONLY, 0, ch.size());
        }
        BufferedStations bufferedStations = new BufferedStations(stringTable, stationsBuffer);

        ByteBuffer transfersBuffer;
        try (FileChannel ch = FileChannel.open(directory.resolve("transfers.bin"))) {
            transfersBuffer = ch.map(FileChannel.MapMode.READ_ONLY, 0, ch.size());
        }
        BufferedTransfers bufferedTransfers = new BufferedTransfers(transfersBuffer);

        ByteBuffer stationAliasesBuffer;
        try (FileChannel ch = FileChannel.open(directory.resolve("station-aliases.bin"))) {
            stationAliasesBuffer = ch.map(FileChannel.MapMode.READ_ONLY, 0, ch.size());
        }
        BufferedStationAliases bufferedStationAliases =
                new BufferedStationAliases(stringTable, stationAliasesBuffer);

        ByteBuffer routesBuffer;
        try (FileChannel ch = FileChannel.open(directory.resolve("routes.bin"))) {
            routesBuffer = ch.map(FileChannel.MapMode.READ_ONLY, 0, ch.size());
        }
        BufferedRoutes bufferedRoutes = new BufferedRoutes(stringTable, routesBuffer);

        ByteBuffer platformsBuffer;
        try (FileChannel ch = FileChannel.open(directory.resolve("platforms.bin"))) {
            platformsBuffer = ch.map(FileChannel.MapMode.READ_ONLY, 0, ch.size());
        }
        BufferedPlatforms bufferedPlatforms = new BufferedPlatforms(stringTable, platformsBuffer);

        return new FileTimeTable(directory,
                stringTable,
                bufferedStations,
                bufferedStationAliases,
                bufferedPlatforms,
                bufferedRoutes,
                bufferedTransfers);
    }

    /**
     * Returns the stations data.
     *
     * @return the stations data
     */
    @Override
    public Stations stations() {
        return stations;
    }

    /**
     * Returns the station aliases data.
     *
     * @return the station aliases data
     */
    @Override
    public StationAliases stationAliases() {
        return stationAliases;
    }

    /**
     * Returns the platforms data.
     *
     * @return the platforms data
     */
    @Override
    public Platforms platforms() {
        return platforms;
    }

    /**
     * Returns the routes data.
     *
     * @return the routes data
     */
    @Override
    public Routes routes() {
        return routes;
    }

    /**
     * Returns the transfers data.
     *
     * @return the transfers data
     */
    @Override
    public Transfers transfers() {
        return transfers;
    }

    /**
     * Loads and returns the trips data for the given date.
     *
     * @param date the travel date
     * @return the trips data
     * @throws UncheckedIOException if an I/O error occurs
     */
    @Override
    public Trips tripsFor(LocalDate date) {
        Path trips = directory.resolve(date.toString()).resolve("trips.bin");
        try (FileChannel trip = FileChannel.open(trips)) {
            ByteBuffer tripsBuffer =
                    trip.map(FileChannel.MapMode.READ_ONLY, 0, trip.size());
            return new BufferedTrips(stringTable, tripsBuffer);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Loads and returns the connections data for the given date.
     *
     * @param date the travel date
     * @return the connections data
     * @throws UncheckedIOException if an I/O error occurs
     */
    @Override
    public Connections connectionsFor(LocalDate date) {
        Path connections = directory.resolve(date.toString()).resolve("connections.bin");
        Path successors = directory.resolve(date.toString()).resolve("connections-succ.bin");
        BufferedConnections bufferedConnections;
        try (FileChannel connection = FileChannel.open(connections);
             FileChannel succConnection = FileChannel.open(successors)) {
            ByteBuffer connectionsBuffer =
                    connection.map(FileChannel.MapMode.READ_ONLY, 0, connection.size());
            ByteBuffer succBuffer =
                    succConnection.map(FileChannel.MapMode.READ_ONLY, 0, succConnection.size());
            bufferedConnections = new BufferedConnections(connectionsBuffer, succBuffer);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return bufferedConnections;
    }
}